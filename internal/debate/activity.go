// Активность дебата: уведомления о текущей стадии для отображения
// пользователю (спиннер в CLI).
package debate

// NotifyFunc — колбэк активности: вызывается перед каждым обращением
// к LLM участника. participantID — идентификатор участника, stage —
// человекочитаемая стадия («предлагает решение», «критикует оппонента»).
//
// Колбэк может вызываться из нескольких горутин одновременно
// (фазы выполняются параллельно), поэтому реализация обязана быть
// потокобезопасной. Колбэк не должен блокироваться надолго.
type NotifyFunc func(participantID, stage string)

// Стадии протокола дебата для отображения активности.
const (
	StagePropose    = "предлагает решение"
	StageCritique   = "критикует оппонента"
	StageRevise     = "пересматривает решение"
	StageConsensus  = "оценивает консенсус"
	StageSimilarity = "сверяет формулировки"
)
